-- ─── (1) الأساس: أقسام / فروع / مستخدمون (مع كسر التبعية الدائرية) ─────
CREATE TABLE IF NOT EXISTS departments (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS branches (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  address    TEXT,
  manager_id BIGINT,                    -- FK يُضاف بعد users
  is_active  BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name         TEXT NOT NULL,
  username          TEXT NOT NULL UNIQUE,
  password_plain    TEXT NOT NULL,
  email             TEXT UNIQUE,
  mobile_number     TEXT,
  role              TEXT NOT NULL,
  status            TEXT NOT NULL DEFAULT 'active',
  is_active         BOOLEAN DEFAULT TRUE,
  branch_id         BIGINT REFERENCES branches(id) ON DELETE SET NULL,
  department_id     BIGINT REFERENCES departments(id),
  direct_manager_id BIGINT REFERENCES users(id),
  auth_id           UUID UNIQUE,
  avatar_url        TEXT,
  nationality       TEXT,
  position_title    TEXT,
  joining_date      DATE,
  last_login_at     TIMESTAMPTZ,
  last_active_at    TIMESTAMPTZ,
  created_at        TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT users_role_check CHECK (role = ANY (ARRAY[
    'admin','company_manager','department_manager','projects_manager','development_manager',
    'meeting_organizer','branch_manager','deputy_manager','hr_manager','payroll_officer',
    'finance_manager','gl_accountant','ap_officer','ap_accountant','ar_officer',
    'operations_manager','maintenance_officer','quality_manager','procurement_manager',
    'delivery_manager','customer_service_manager','cc_manager','bi_analyst',
    'integrations_admin','franchise_manager','legal_officer','employee'])),
  CONSTRAINT users_status_check CHECK (status = ANY (ARRAY['active','inactive','suspended']))
);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='branches_manager_id_fkey') THEN
    ALTER TABLE branches ADD CONSTRAINT branches_manager_id_fkey
      FOREIGN KEY (manager_id) REFERENCES users(id) ON DELETE SET NULL;
  END IF;
END $$;

-- ─── (2) الصلاحيات ─────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS role_permissions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role        TEXT NOT NULL,
  section_key TEXT NOT NULL,
  can_view    BOOLEAN NOT NULL DEFAULT FALSE,
  can_manage  BOOLEAN NOT NULL DEFAULT FALSE,
  scope       TEXT NOT NULL DEFAULT 'company_wide',
  CONSTRAINT role_permissions_scope_check CHECK (scope = ANY (ARRAY['company_wide','own_department'])),
  CONSTRAINT role_permissions_role_section_key_key UNIQUE (role, section_key)
