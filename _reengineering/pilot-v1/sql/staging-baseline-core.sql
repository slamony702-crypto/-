-- ─── (3) الاجتماعات ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS meetings (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title              TEXT NOT NULL,
  meeting_type       TEXT NOT NULL,
  meeting_datetime   TIMESTAMPTZ NOT NULL,
  location_type      TEXT NOT NULL,
  location_detail    TEXT,
  department_id      BIGINT REFERENCES departments(id),
  organizer_id       BIGINT REFERENCES users(id),
  status             TEXT NOT NULL DEFAULT 'scheduled',
  summary            TEXT,
  minutes_file_url   TEXT, minutes_file_name TEXT, minutes_notes TEXT,
  minutes_uploaded_at TIMESTAMPTZ,
  minutes_uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at         TIMESTAMPTZ DEFAULT NOW(),
  updated_at         TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT meetings_status_check CHECK (status = ANY (ARRAY['scheduled','done','in_follow_up','closed','postponed','cancelled'])),
  CONSTRAINT meetings_location_type_check CHECK (location_type = ANY (ARRAY['in_person','online'])),
  CONSTRAINT meetings_meeting_type_check CHECK (meeting_type = ANY (ARRAY['weekly','emergency','administrative','financial','sales','operations']))
